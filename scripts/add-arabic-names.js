//updating in both files
const files = ['countries.json', 'countries-emoji.json']

files.forEach((fileName) => {
  const filePath = path.join(__dirname, '..', 'data', fileName)
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'))

  Object.keys(data).forEach((countryCode) => {
    if (data[countryCode].name && arabicNames[countryCode]) {
      data[countryCode].name.ara = arabicNames[countryCode]
    }
  })

  fs.writeFileSync(filePath, JSON.stringify(data, null, 2))
  console.log(`Updated ${fileName} with Arabic names`)
})
